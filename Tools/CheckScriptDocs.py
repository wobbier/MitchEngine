#!/usr/bin/env python3
"""The C# scripting API's documentation (CS-10): build ScriptCore with XML docs, hold the line on
undocumented public members, and write the API reference.

    python3 Engine/Tools/CheckScriptDocs.py            # check (RunChecks' "Script API docs" step)
    python3 Engine/Tools/CheckScriptDocs.py --update   # accept fewer undocumented members
    python3 Engine/Tools/CheckScriptDocs.py --markdown # rewrite Docs/API/ScriptCore.md

The check fails on badly formed doc comments (CS1570 and friends), on a Docs/API/ScriptCore.md that
doesn't match the comments, and when any source file has more
undocumented public members (CS1591) than Tools/ScriptDocsBaseline.json allows: the baseline only
goes down (--update lowers it after documenting). Generated interop and the SDL key enums opt out
with #pragma. Run from the repository root inside the dev shell.
"""
import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from pathlib import Path

ENGINE = Path(__file__).resolve().parents[1]
PROJECT = ENGINE / "Modules/ScriptCore/ScriptCore.csproj"
SOURCE = ENGINE / "Modules/ScriptCore/Source"
BASELINE = ENGINE / "Tools/ScriptDocsBaseline.json"
MARKDOWN = ENGINE / "Docs/API/ScriptCore.md"
WARNING = re.compile(r"^(?P<file>[^(\s][^(]*)\((?P<line>\d+),\d+\): warning (?P<code>CS\d+): (?P<text>.*?)(?: \[.*\])?$")
BAD_XML = {"CS1570", "CS1571", "CS1572", "CS1573", "CS1574", "CS1580", "CS1581", "CS1584", "CS1587"}


def build(artifacts):
    command = ["dotnet", "build", str(PROJECT), "-p:GenerateDocumentationFile=true", "--artifacts-path", str(artifacts), "--no-incremental", "-v", "q", "-nologo"]
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode != 0:
        sys.stdout.write(result.stdout + result.stderr)
        raise SystemExit("ScriptCore didn't build")
    seen = set()
    warnings = []
    for line in result.stdout.splitlines():
        match = WARNING.match(line.strip())
        if match and (match["file"], match["line"], match["code"], match["text"]) not in seen:
            seen.add((match["file"], match["line"], match["code"], match["text"]))
            warnings.append(match)
    xml = next(Path(artifacts).rglob("ScriptCore.xml"), None)
    return warnings, xml


def relative(path):
    try:
        return Path(path).resolve().relative_to(SOURCE).as_posix()
    except ValueError:
        return Path(path).name


def markdown(xml):
    """The documented members, by type: a plain reference until a docs site exists."""
    members = defaultdict(list)
    types = {}
    for member in ET.parse(xml).getroot().iter("member"):
        name = member.get("name", "")
        kind, _, full = name.partition(":")
        summary = " ".join((member.findtext("summary") or "").split())
        if kind == "T":
            types[full] = summary
            continue
        owner = full.split("(")[0].rsplit(".", 1)[0]
        members[owner].append((kind, full[len(owner) + 1:], summary))
    labels = {"M": "method", "P": "property", "F": "field", "E": "event"}
    lines = ["# ScriptCore API", "",
             "> Generated by `Engine/Tools/CheckScriptDocs.py --markdown` from the XML doc comments (CS-10). Edit the comments, not this page.",
             "> Members without a comment aren't listed yet; `Tools/ScriptDocsBaseline.json` counts them per file.", ""]
    for type_name in sorted(set(types) | set(members), key=str.lower):
        short = type_name.replace("ScriptCore.", "", 1)
        lines.append(f"## {short}")
        lines.append("")
        if types.get(type_name):
            lines.append(types[type_name])
            lines.append("")
        for kind, member, summary in sorted(members.get(type_name, []), key=lambda m: m[1].lower()):
            member = member.replace("#ctor", "(constructor)").replace("`", "")
            lines.append(f"- `{member}` ({labels.get(kind, kind)}): {summary}" if summary else f"- `{member}` ({labels.get(kind, kind)})")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update", action="store_true", help="lower the baseline to the current counts")
    parser.add_argument("--markdown", action="store_true", help="rewrite Docs/API/ScriptCore.md")
    parser.add_argument("--artifacts", default=".tmp/DotNet/ScriptDocs")
    args = parser.parse_args()

    warnings, xml = build(Path(args.artifacts).resolve())
    bad = [w for w in warnings if w["code"] in BAD_XML]
    undocumented = Counter(relative(w["file"]) for w in warnings if w["code"] == "CS1591")
    for w in bad:
        print(f"bad doc comment: {relative(w['file'])}:{w['line']}: {w['code']} {w['text']}")

    baseline = json.loads(BASELINE.read_text()) if BASELINE.exists() else {}
    grown = {f: (n, baseline.get(f, 0)) for f, n in undocumented.items() if n > baseline.get(f, 0)}
    for file, (now, allowed) in sorted(grown.items()):
        print(f"undocumented public members in {file}: {now} (baseline {allowed}); document them (/// <summary>)")
    total = sum(undocumented.values())
    print(f"{total} undocumented public members (baseline {sum(baseline.values())}), {len(bad)} bad doc comments")

    if args.update:
        if bad:
            raise SystemExit("fix the bad doc comments before updating the baseline")
        # Only ever down: a file's allowance never rises through --update.
        lowered = {f: min(n, baseline[f]) if f in baseline else n for f, n in undocumented.items() if n}
        BASELINE.write_text(json.dumps(dict(sorted(lowered.items())), indent=4) + "\n")
        print(f"baseline: {sum(lowered.values())}")
    stale = False
    if xml:
        text = markdown(xml)
        if args.markdown:
            MARKDOWN.parent.mkdir(parents=True, exist_ok=True)
            MARKDOWN.write_text(text, encoding="utf-8")
            print(f"wrote {MARKDOWN.relative_to(ENGINE.parent)}")
        elif not MARKDOWN.exists() or MARKDOWN.read_text(encoding="utf-8") != text:
            stale = True
            print(f"{MARKDOWN.relative_to(ENGINE.parent)} is out of date with the doc comments: run with --markdown")
    if bad or stale or (grown and not args.update):
        sys.exit(1)


if __name__ == "__main__":
    main()
