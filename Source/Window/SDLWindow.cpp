void SDLWindow::SetWindow( SDL_Window* window )
{
    SDL_SysWMinfo wmi;

    SDL_VERSION( &wmi.version );
    if( !SDL_GetWindowWMInfo( window, &wmi ) )
    {
        return;
    }
    printf("Subsystem: %d\n", wmi.subsystem);

#if USING( ME_PLATFORM_WIN64 )
    NativeDisplay = nullptr;
    NativeWindow = wmi.info.win.window;
#endif
#if USING( ME_PLATFORM_MACOS )
    NativeDisplay = nullptr;
    NativeWindow = wmi.info.cocoa.window;
#endif
#if USING( ME_PLATFORM_UWP )
    NativeDisplay = nullptr;
    NativeWindow = wmi.info.win.window;
#endif
#if USING( ME_PLATFORM_LINUX )
    switch (wmi.subsystem)
    {
        case SDL_SYSWM_WAYLAND:
            NativeDisplay  = wmi.info.wl.display;
            NativeWindow  = wmi.info.wl.surface;
            NativeWindowType = bgfx::NativeWindowHandleType::Wayland;
            break;

        case SDL_SYSWM_X11:
            // X11: ndt = Display*, nwh = Window
            NativeDisplay = wmi.info.x11.display;
            NativeWindow = (void*)(uintptr_t)wmi.info.x11.window;
            break;

        default:
            printf("Unhandled SDL WM subsystem: %d\n", (int)wmi.subsystem);
            break;
    }
#endif
}

void SDLWindow::HandleWindowEvent( const SDL_WindowEvent& event )
{
    // ImGui's SDL backend handles detached window events. They must not resize, move or close
    // the engine's main window (closing a panel used to quit the editor here).
    if( event.windowID != SDL_GetWindowID( WindowHandle ) )
        return;
    if( event.type != SDL_WINDOWEVENT )
    {
        YIKES( "Event Type Mismatch: Expected WindowEvent" );
        return;
    }
    switch( event.event ) {
    case SDL_WINDOWEVENT_SHOWN:
        //SDL_Log("Window %d shown", event.windowID);
        break;
    case SDL_WINDOWEVENT_HIDDEN:
        //SDL_Log("Window %d hidden", event.windowID);
        break;
    case SDL_WINDOWEVENT_EXPOSED:
        //SDL_Log("Window %d exposed", event.windowID);
        break;
    case SDL_WINDOWEVENT_MOVED:
    {
        SDL_Log( "Window %d moved to %d,%d",
            event.windowID, event.data1,
            event.data2 );
        WindowMovedEvent evt;
        evt.NewPosition = { event.data1, event.data2 };
        evt.Fire();
        break;
    }
    case SDL_WINDOWEVENT_RESIZED:
        SDL_Log( "Window %d resized to %dx%d",
            event.windowID, event.data1,
            event.data2 );
        break;
    case SDL_WINDOWEVENT_SIZE_CHANGED:
        ResizeCB( GetSize() );
        break;
    case SDL_WINDOWEVENT_MINIMIZED:
        SDL_Log( "Window %d minimized", event.windowID );
        break;
    case SDL_WINDOWEVENT_MAXIMIZED:
        isMaximized = true;
        SDL_Log( "Window %d maximized", event.windowID );
        break;
    case SDL_WINDOWEVENT_RESTORED:
        isMaximized = false;
        SDL_Log( "Window %d restored", event.windowID );
        break;
    case SDL_WINDOWEVENT_ENTER:
        //SDL_Log("Mouse entered window %d",
            //event.windowID);
        break;
    case SDL_WINDOWEVENT_LEAVE:
        //SDL_Log("Mouse left window %d", event.windowID);
        break;
    case SDL_WINDOWEVENT_FOCUS_GAINED:
        //SDL_Log("Window %d gained keyboard focus",
            //event.windowID);
        break;
    case SDL_WINDOWEVENT_FOCUS_LOST:
        //SDL_Log("Window %d lost keyboard focus",
            //event.windowID);
        break;
    case SDL_WINDOWEVENT_CLOSE:
        CloseRequested = true;
        SDL_Log( "Window %d closed", event.windowID );
        break;
#if SDL_VERSION_ATLEAST(2, 0, 5)
    case SDL_WINDOWEVENT_TAKE_FOCUS:
        SDL_Log( "Window %d is offered a focus", event.windowID );
        break;
    case SDL_WINDOWEVENT_HIT_TEST:
        //SDL_Log("Window %d has a special hit test", event.windowID);
        break;
#endif
    default:
        SDL_Log( "Window %d got unknown event %d",
            event.windowID, event.event );
        break;
    }
}
