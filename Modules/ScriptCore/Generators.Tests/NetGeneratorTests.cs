    private static void AssertSingleError(GeneratorDriverTests.RunResult result, string id)
    {
        Assert.Contains(result.GeneratorDiagnostics, d => d.Id == id && d.Severity == DiagnosticSeverity.Error);
        Assert.All(result.GeneratorDiagnostics, d => Assert.Equal(id, d.Id));
        Assert.Equal("", NetSource(result));
    }


