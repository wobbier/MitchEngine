using System.Linq;
using Microsoft.CodeAnalysis;
using MitchEngine.Generators;
using Xunit;

// NET-6: the NetGenerator on in-memory compilations (snapshot, hash, diagnostics).
public class NetGeneratorTests
{
    private static GeneratorDriverTests.RunResult RunNet(string source) => GeneratorDriverTests.Run(source, new NetGenerator());


    private static string NetSource(GeneratorDriverTests.RunResult result)
        => result.Sources.Where(p => p.Key.EndsWith(".Net.g.cs")).Select(p => p.Value).SingleOrDefault() ?? "";


    private static string HashOf(string generated) => generated.Split('\n').Single(l => l.Contains("__NetSchemaHash =")).Trim();


    [Fact]
    public void Snapshot_of_a_minimal_net_type()
    {
        var result = RunNet(@"using ScriptCore;

public partial class MiniNet : Script
{
    [Predicted] public float Stamina;
    [Replicated] public int Score;

    [ServerRpc] partial void Fire(int shot);
    [ClientRpc(NetTarget.Owner)] partial void Hit(Vector3 at);

    void OnFire(int shot) { }
    void OnHit(Vector3 at) { }
}
");
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Empty(result.CompileDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));
        Assert.Equal(new[] { "MiniNet.Net.g.cs" }, result.Sources.Keys.ToArray());

        const string expected = @"// <auto-generated by MitchEngine.Generators (NET-6); do not edit.>
#nullable enable
#pragma warning disable

partial class MiniNet : global::ScriptCore.INetScript
{
    /// <summary>Generated net layout hash (NET-6): peers must agree on it in the session handshake.</summary>
    public const ulong __NetSchemaHash = 0x40AB1CECDDE59FC5UL;

    int global::ScriptCore.INetScript.NetFlags => 7;

    int global::ScriptCore.INetScript.NetSavePredicted( global::System.Span<byte> destination )
    {
        if( destination.Length < 4 )
        {
            return 4;
        }
        var writer = new global::ScriptCore.NetWriter( destination );
        writer.WriteFloat( this.Stamina );
        return 4;
    }

    void global::ScriptCore.INetScript.NetRestorePredicted( global::System.ReadOnlySpan<byte> source )
    {
        if( source.Length < 4 )
        {
            return;
        }
        var reader = new global::ScriptCore.NetReader( source );
        this.Stamina = reader.ReadFloat();
    }

    int global::ScriptCore.INetScript.NetWriteReplicated( global::System.Span<byte> destination )
    {
        if( destination.Length < 8 )
        {
            return 8;
        }
        var writer = new global::ScriptCore.NetWriter( destination );
        writer.WriteFloat( this.Stamina );
        writer.WriteInt( this.Score );
        return 8;
    }

    void global::ScriptCore.INetScript.NetReadReplicated( global::System.ReadOnlySpan<byte> source, bool skipPredicted )
    {
        if( source.Length < 8 )
        {
            return;
        }
        var reader = new global::ScriptCore.NetReader( source );
        if( skipPredicted ) { reader.Skip( 4 ); } else { this.Stamina = reader.ReadFloat(); }
        this.Score = reader.ReadInt();
    }

    void global::ScriptCore.INetScript.NetDispatchRpc( int rpcId, global::System.ReadOnlySpan<byte> args )
    {
        var reader = new global::ScriptCore.NetReader( args );
        switch( rpcId )
        {
            case 0:
            {
                if( global::ScriptCore.Net.IsClient ) { return; }
                var a0 = reader.ReadInt();
                if( reader.Overflowed )
                {
                    return;
                }
                this.OnFire( a0 );
                return;
            }
            case 1:
            {
                if( global::ScriptCore.Net.IsServer ) { return; }
                var a0 = reader.ReadVector3();
                if( reader.Overflowed )
                {
                    return;
                }
                this.OnHit( a0 );
                return;
            }
        }
    }

    partial void Fire( int shot )
    {
        global::System.Span<byte> __buffer = stackalloc byte[4];
        var __writer = new global::ScriptCore.NetWriter( __buffer );
        __writer.WriteInt( shot );
        global::ScriptCore.Net.SendRpc( this.Entity, 0, 0, __writer.Written, this );
    }

    partial void Hit( global::Vector3 at )
    {
        global::System.Span<byte> __buffer = stackalloc byte[12];
        var __writer = new global::ScriptCore.NetWriter( __buffer );
        __writer.WriteVector3( at );
        global::ScriptCore.Net.SendRpc( this.Entity, 1, 1, __writer.Written, this );
    }
}
";
        Assert.Equal(GeneratorDriverTests.Normalize(expected), GeneratorDriverTests.Normalize(result.Generated));
    }


    [Fact]
    public void Net_hash_is_stable_and_layout_sensitive()
    {
        const string template = @"using ScriptCore;
public partial class Hashed : Script
{
    [FIELD_ATTR] public FIELD_TYPE FIELD_NAME;
    RPC_ATTR partial void Ping(int value);
    void OnPing(int value) { }
}
";
        string Make(string fieldAttr = "Replicated", string fieldType = "int", string fieldName = "A", string rpcAttr = "[ServerRpc]")
            => template.Replace("FIELD_ATTR", fieldAttr).Replace("FIELD_TYPE", fieldType).Replace("FIELD_NAME", fieldName).Replace("RPC_ATTR", rpcAttr);

        var first = RunNet(Make());
        var second = RunNet(Make());
        Assert.Empty(first.GeneratorDiagnostics);
        Assert.Equal(NetSource(first), NetSource(second));

        var baseline = HashOf(NetSource(first));
        Assert.NotEqual(baseline, HashOf(NetSource(RunNet(Make(fieldName: "B")))));
        Assert.NotEqual(baseline, HashOf(NetSource(RunNet(Make(fieldType: "float")))));
        Assert.NotEqual(baseline, HashOf(NetSource(RunNet(Make(fieldAttr: "Predicted")))));
        Assert.NotEqual(baseline, HashOf(NetSource(RunNet(Make(rpcAttr: "[ClientRpc]")))));
        var all = HashOf(NetSource(RunNet(Make(rpcAttr: "[ClientRpc(NetTarget.All)]"))));
        var owner = HashOf(NetSource(RunNet(Make(rpcAttr: "[ClientRpc(NetTarget.Owner)]"))));
        Assert.NotEqual(all, owner);
        Assert.Equal(HashOf(NetSource(RunNet(Make(rpcAttr: "[ClientRpc]")))), all);
    }


    [Fact]
    public void Rpc_ids_follow_ordinal_name_order_and_modifiers_are_kept()
    {
        var result = RunNet(@"using ScriptCore;
namespace Game.Net
{
    public partial class Ordered : Script
    {
        [ClientRpc] public partial void b(string text, Entity who);
        [ServerRpc] partial void Z();
        [ServerRpc] partial void a(@int @class);
        void Onb(string text, Entity who) { }
        void OnZ() { }
        void Ona(@int @class) { }
    }
    public enum @int { One }
}
");
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Empty(result.CompileDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));
        var generated = NetSource(result);
        Assert.Contains("namespace Game.Net", generated);
        // Ordinal: Z < a < b.
        Assert.Contains("global::ScriptCore.Net.SendRpc( this.Entity, 0, 0, default, this );", generated);
        Assert.Contains("partial void a( global::Game.Net.@int @class )", generated);
        Assert.Contains("global::ScriptCore.Net.SendRpc( this.Entity, 1, 0, __writer.Written, this );", generated);
        Assert.Contains("public partial void b( string text, global::ScriptCore.Entity who )", generated);
        Assert.Contains("stackalloc byte[1008]", generated);
        Assert.Contains("global::ScriptCore.Net.SendRpc( this.Entity, 2, 2, __writer.Written, this );", generated);
        Assert.Contains("int global::ScriptCore.INetScript.NetFlags => 4;", generated);
    }


    [Fact]
    public void Schema_and_net_generators_coexist_without_changing_the_schema()
    {
        const string source = @"using ScriptCore;
using ScriptCore.Generation;

[GenerateSchema]
public partial class Both : Script
{
    public float Speed;
    [Replicated] public int Score;
    [ServerRpc] partial void Ping(int value);
    void OnPing(int value) { }
}
";
        var schemaOnly = GeneratorDriverTests.Run(source, new SchemaGenerator());
        var both = GeneratorDriverTests.Run(source, new SchemaGenerator(), new NetGenerator());
        Assert.Empty(both.GeneratorDiagnostics);
        Assert.Empty(both.CompileDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));
        Assert.Equal(schemaOnly.Sources["Both.Schema.g.cs"], both.Sources["Both.Schema.g.cs"]);
        Assert.True(both.Sources.ContainsKey("Both.Net.g.cs"));
    }


    [Fact]
    public void Same_named_attributes_from_elsewhere_are_ignored()
    {
