    [Fact]
    public void Keyword_names_are_escaped_in_generated_code()
    {
        var result = RunNet(@"using ScriptCore;
public partial class @class : Script
{
    [Replicated] public int @event;
    [Predicted] public float @fixed;
    [ServerRpc] partial void @checked(int @in);
    void Onchecked(int value) { }
}
");
        Assert.Empty(result.GeneratorDiagnostics);
        Assert.Empty(result.CompileDiagnostics.Where(d => d.Severity == DiagnosticSeverity.Error));
        var generated = NetSource(result);
        Assert.Contains("partial class @class", generated);
        Assert.Contains("this.@event", generated);
        Assert.Contains("partial void @checked(", generated);
    }


    [Fact]
    public void Rpc_dispatch_only_runs_on_the_side_it_is_addressed_to()
    {
        var generated = NetSource(RunNet(@"using ScriptCore;
public partial class Sides : Script
{
    [ServerRpc] partial void Up(int value);
    [ClientRpc(NetTarget.All)] partial void Down(int value);
    void OnUp(int value) { }
    void OnDown(int value) { }
}
"));
        // Ordinal order: Down = 0 (a ClientRpc), Up = 1 (a ServerRpc).
        var down = generated.IndexOf("case 0:");
        var up = generated.IndexOf("case 1:");
        Assert.True(down >= 0 && up > down);
        Assert.Contains("if( global::ScriptCore.Net.IsServer ) { return; }", generated.Substring(down, up - down));
        Assert.Contains("if( global::ScriptCore.Net.IsClient ) { return; }", generated.Substring(up));
    }
